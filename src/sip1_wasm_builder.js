"use strict";

const fs = require("fs");
const path = require("path");

// Bytecode verified:
// func 0 (i32, i32) -> i32: (arg0 ^ arg1) * 16777619
// func 1 () -> i32: return 102
const SIP1_WASM_BINARY = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  // Section 1: Type
  0x01, 0x0b, 0x02,
  0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f,
  0x60, 0x00, 0x01, 0x7f,
  // Section 3: Function
  0x03, 0x03, 0x02, 0x00, 0x01,
  // Section 7: Export
  0x07, 0x25, 0x02,
  0x0b, 0x73, 0x69, 0x70, 0x31, 0x4d, 0x69, 0x78, 0x48, 0x61, 0x73, 0x68, 0x00, 0x00,
  0x13, 0x73, 0x69, 0x70, 0x31, 0x50, 0x72, 0x6f, 0x74, 0x6f, 0x63, 0x6f, 0x6c, 0x56, 0x65, 0x72, 0x73, 0x69, 0x6f, 0x6e, 0x00, 0x01,
  // Section 10: Code
  0x0a, 0x15, 0x02,
  0x0d, 0x00, 0x20, 0x00, 0x20, 0x01, 0x73, 0x41, 0x93, 0x83, 0x80, 0x08, 0x6c, 0x0b,
  0x05, 0x00, 0x41, 0xe6, 0x00, 0x0b
]);

function buildAndSaveWasmBinary(outPath) {
  const target = outPath || path.join(__dirname, "../dist/sip1_core.wasm");
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, Buffer.from(SIP1_WASM_BINARY));
  return target;
}

function loadSip1WasmKernelSync() {
  if (!WebAssembly.validate(SIP1_WASM_BINARY)) {
    throw new Error("ERR_WASM_VALIDATION_FAILED");
  }
  const mod = new WebAssembly.Module(SIP1_WASM_BINARY);
  const inst = new WebAssembly.Instance(mod, {});
  return {
    validated: true,
    byteLength: SIP1_WASM_BINARY.byteLength,
    exports: inst.exports
  };
}

module.exports = {
  SIP1_WASM_BINARY,
  buildAndSaveWasmBinary,
  loadSip1WasmKernelSync
};
